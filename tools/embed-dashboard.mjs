// Regenerate src/dashboard.ts from src/dashboard.html.
// Run: node tools/embed-dashboard.mjs   (or: bun tools/embed-dashboard.mjs)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const html = readFileSync(join(root, "src/dashboard.html"), "utf8");
// Escape for embedding in a template literal: backslash, backtick, ${
const esc = html.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
const out = `// GENERATED by tools/embed-dashboard.mjs — do not edit. Source: src/dashboard.html\nexport const DASHBOARD_HTML = \`${esc}\`;\n`;
writeFileSync(join(root, "src/dashboard.ts"), out);
console.log(`dashboard.ts written (${html.length} bytes of HTML)`);
